const NAV_ENTRIES: { label: string; href: string; icon: ReactNode }[] = [
  { label: "My Profile", href: "/admin/dashboard", icon: <ProfileIcon /> },
  { label: "Team Members", href: "/admin/members", icon: <UsersIcon /> },
  { label: "Sponsors", href: "/admin/sponsors", icon: <BriefcaseIcon /> },
  { label: "Audit Logs", href: "/admin/audit-logs", icon: <HistoryIcon /> },
];

/** Sidebar nav for the given role, with links the role can't open hidden. */
export function buildAdminNav(role: UserRole, activeHref: string) {
  return NAV_ENTRIES.filter((entry) => canAccessRoute(entry.href, role)).map((entry) => ({
    ...entry,
    active: entry.href === activeHref,
  }));
}
